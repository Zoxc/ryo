//! The JIT's handler effect table (`jit::effects`) for the Lean side: every full opcode's
//! `effects`, written as `lean/RyoTest/EffectsVectors.lean`, which `RyoTest/Effects.lean`
//! checks against opSem's footprints (`Ryo/Vm/OpSem/Footprint.lean`), so the two can't drift.
//! With `RYO_LEAN_GEN=1` the test rewrites that file, else it checks it is up to date.

use std::fmt::Write as _;

use ryo_bytecode::full::ALL_OPCODES;
use ryo_bytecode::jit::effects::{Effect, effects};

fn effect(e: &Option<Effect>) -> String {
    match e {
        None => "none".into(),
        Some(Effect::Read(n)) => format!("some (.read {n})"),
        Some(Effect::Write(n)) => format!("some (.write {n})"),
        Some(Effect::Update(n)) => format!("some (.update {n})"),
        Some(Effect::Addr) => "some .addr".into(),
        Some(Effect::Block) => "some .block".into(),
    }
}

fn vectors() -> String {
    let mut s = String::new();
    s.push_str(
        "/-\nGenerated by `vm/bytecode/tests/lean_effects.rs` (`RYO_LEAN_GEN=1 cargo test --test lean_effects`\nin `vm/`): \
         every full opcode's `jit::effects`, which `RyoTest/Effects.lean` checks against opSem's\nfootprints. Do not edit.\n-/\n\n\
         namespace RyoTest.EffectsVectors\n\n\
         /-- `jit::effects::Effect`. -/\ninductive Effect where\n  | read (n : Nat)\n  | write (n : Nat)\n  | update (n : Nat)\n  \
         | addr\n  | block\nderiving Repr, DecidableEq\n\n\
         /-- `jit::effects::Effects`: per operand (in `OpInfo.operands` order), and `memory`. -/\nstructure Effects where\n  \
         opnds : List (Option Effect)\n  memory : Bool\nderiving Repr, DecidableEq\n\n\
         /-- By mnemonic, every full opcode's `effects` (`none` without a handler). -/\n\
         def effects : List (String × Option Effects) := [\n",
    );
    for (k, &op) in ALL_OPCODES.iter().enumerate() {
        let sep = if k + 1 == ALL_OPCODES.len() { "" } else { "," };
        let mn = op.mnemonic();
        let e = match effects(op) {
            None => "none".to_owned(),
            Some(e) => {
                let n = op.info().operands.len();
                assert!(e.opnds[n..].iter().all(Option::is_none), "{mn}: an effect past the operands");
                let opnds: Vec<String> = e.opnds[..n].iter().map(effect).collect();
                format!("some {{ opnds := [{}], memory := {} }}", opnds.join(", "), e.memory)
            }
        };
        writeln!(s, "  (\"{mn}\", {e}){sep}").unwrap();
    }
    s.push_str("]\n\nend RyoTest.EffectsVectors\n");
    s
}

#[test]
fn lean_effects() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../lean/RyoTest/EffectsVectors.lean");
    let want = vectors();
    if std::env::var_os("RYO_LEAN_GEN").is_some_and(|v| v == "1") {
        std::fs::write(path, want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(path).unwrap_or_default();
    assert!(have == want, "{path} is out of date: regenerate it with RYO_LEAN_GEN=1 cargo test --test lean_effects");
}
