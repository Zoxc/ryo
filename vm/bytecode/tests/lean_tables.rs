fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) { format!("«{s}»") } else { s.to_owned() }
}

/// `AddW32` -> `addW32`.
fn camel(s: &str) -> String {
    let mut c = s.chars();
    let first = c.next().unwrap().to_ascii_lowercase();
    ident(&format!("{first}{}", c.as_str()))
}

fn string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

const ELEM_KINDS: [ElemKind; 8] =
    [ElemKind::Target, ElemKind::Word, ElemKind::Case8, ElemKind::Case16, ElemKind::Case32, ElemKind::Case64, ElemKind::Case128, ElemKind::Arg];

/// Lean constructor of `e` (exhaustive, so a new kind fails to compile here).
fn elem_name(e: ElemKind) -> &'static str {
    match e {
        ElemKind::Target => "target",
        ElemKind::Word => "word",
        ElemKind::Case8 => "case8",
        ElemKind::Case16 => "case16",
        ElemKind::Case32 => "case32",
        ElemKind::Case64 => "case64",
        ElemKind::Case128 => "case128",
        ElemKind::Arg => "arg",
    }
}

/// Every operand kind but the lists, and `list` itself (its constructor name).
const OPERAND_KINDS: [OperandKind; 15] = [
    OperandKind::Slot,
    OperandKind::Mem,
    OperandKind::U8,
    OperandKind::U16,
    OperandKind::U32,
    OperandKind::U64,
    OperandKind::I64,
    OperandKind::U128,
    OperandKind::Const,
    OperandKind::Abs,
    OperandKind::Sym,
    OperandKind::Func,
    OperandKind::Target,
    OperandKind::Neg,
    OperandKind::Handler,
];

fn all_operand_kinds() -> Vec<OperandKind> {
    let mut v = OPERAND_KINDS.to_vec();
    v.extend(ELEM_KINDS.iter().map(|&e| OperandKind::List(e)));
    v
}

fn kind_name(k: OperandKind) -> &'static str {
    match k {
        OperandKind::Slot => "slot",
        OperandKind::Mem => "mem",
        OperandKind::U8 => "u8",
        OperandKind::U16 => "u16",
        OperandKind::U32 => "u32",
        OperandKind::U64 => "u64",
        OperandKind::I64 => "i64",
        OperandKind::U128 => "u128",
        OperandKind::Const => "const",
        OperandKind::Abs => "abs",
        OperandKind::Sym => "sym",
        OperandKind::Func => "func",
        OperandKind::Target => "target",
        OperandKind::Neg => "neg",
        OperandKind::List(_) => "list",
        OperandKind::Handler => "handler",
    }
}

fn kind_term(k: OperandKind) -> String {
    match k {
        OperandKind::List(e) => format!("(OperandKind.list ElemKind.{})", elem_name(e)),
        k => format!("OperandKind.{}", kind_name(k)),
    }
}

const SHAPES: [Shape; 11] =
    [Shape::Op, Shape::Br, Shape::Switch, Shape::Trap, Shape::Ret, Shape::Jmp, Shape::Call, Shape::TailCall, Shape::Island, Shape::Lpad, Shape::Arg];

fn shape_name(s: Shape) -> &'static str {
    match s {
        Shape::Op => "op",
        Shape::Br => "br",
        Shape::Switch => "switch",
        Shape::Trap => "trap",
        Shape::Ret => "ret",
        Shape::Jmp => "jmp",
        Shape::Call => "call",
        Shape::TailCall => "tailCall",
        Shape::Island => "island",
        Shape::Lpad => "lpad",
        Shape::Arg => "arg",
    }
}

/// `reduced::Arg`'s variants, one of each, with their Lean constructors.
fn args() -> Vec<(Arg, &'static str)> {
    let all = vec![
        (Arg::Fp, "fp"),
        (Arg::Exception, "exception"),
        (Arg::Imm(0), "imm"),
        (Arg::Const(full::Const(0)), "const"),
        (Arg::Data(full::Data(0)), "data"),
        (Arg::Sym(full::Sym(0)), "sym"),
        (Arg::Ro(0), "ro"),
    ];
    for (a, _) in &all {
        // Exhaustive, so a new variant fails to compile here.
        match a {
            Arg::Fp | Arg::Exception | Arg::Imm(_) | Arg::Const(_) | Arg::Data(_) | Arg::Sym(_) | Arg::Ro(_) => {}
        }
    }
    all
}

