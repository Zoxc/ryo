/// Array elements, several per line.
fn push_wrapped(s: &mut String, items: &[String]) {
    let mut line = 0;
    for (i, it) in items.iter().enumerate() {
        if line == 0 || line + it.len() > 96 {
            s.push_str("\n  ");
            line = 2;
        } else {
            s.push(' ');
            line += 1;
        }
        s.push_str(it);
        line += it.len();
        if i + 1 < items.len() {
            s.push(',');
            line += 1;
        }
    }
    s.push('\n');
}

fn mode(fp_arg: bool, pe: bool) -> Mode {
    Mode { fp_arg, frame_pointer: true, align_loops: false, pe, counters: false, far_rt: false }
}

fn layout_term(op: full::Opcode, l: &Layout) -> String {
    let mut s = String::from("Layout.mk [");
    for (i, loc) in l.locs[..op.info().operands.len()].iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        write!(s, "Loc.mk {} {} {} {}", loc.reg, loc.shift, loc.count, loc.shared).unwrap();
    }
    write!(s, "] {} {}", l.first, l.regs).unwrap();
    s
}

