macro_rules! opt {
    () => {
        None
    };
    ($e:expr) => {
        Some($e)
    };
}

/// `for_each_handler!`'s entries: (opcode, kind, parameters, return type).
macro_rules! collect_handlers {
    (() $($name:ident => $kind:ident ($($p:tt)*) $(-> $ret:ty)?;)*) => {
        &[$((stringify!($name), stringify!($kind), stringify!($($p)*), opt!($(stringify!($ret))?))),*]
    };
}

const HANDLERS: &[(&str, &str, &str, Option<&str>)] = for_each_handler!(collect_handlers!());

