fn opt_nat(v: Option<usize>) -> String {
    match v {
        Some(n) => format!("some {n}"),
        None => "none".to_owned(),
    }
}

fn op_info<O: std::fmt::Debug>(info: &OpInfo<O>) -> String {
    let mut s = format!("OpInfo.mk {} {} Shape.{} [", string(&format!("{:?}", info.opcode)), string(info.mnemonic), shape_name(info.shape));
    for (i, o) in info.operands.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        write!(s, "OperandInfo.mk {} {}", string(o.name), kind_term(o.kind)).unwrap();
    }
    write!(s, "] ({})", opt_nat(info.fixed_len)).unwrap();
    s
}

/// The common part of `Full.lean` and `Reduced.lean`.
fn op_list<O: std::fmt::Debug + 'static>(s: &mut String, ns: &str, infos: &[OpInfo<O>]) {
    writeln!(s, "namespace Ryo.Vm.{ns}\n").unwrap();
    writeln!(s, "/-- The number of opcodes. -/\ndef count : Nat := {}\n", infos.len()).unwrap();
    writeln!(s, "/-- `{}::OP_INFO`, by opcode value. -/\ndef opInfos : Array OpInfo := #[", ns.to_lowercase()).unwrap();
    for (i, info) in infos.iter().enumerate() {
        writeln!(s, "  {}{}", op_info(info), if i + 1 < infos.len() { "," } else { "" }).unwrap();
    }
    s.push_str(
        "]

/-- The opcode of value `n`, if there is one (`Opcode::from_u16`). -/
def Opcode.ofNat? (n : Nat) : Option Opcode :=
  if n < count then some ⟨n.toUInt16⟩ else none

/-- Every opcode, in value order (`ALL_OPCODES`). -/
def all : List Opcode := (List.range count).map fun n => ⟨n.toUInt16⟩

def Opcode.info (op : Opcode) : OpInfo := opInfos[op.val.toNat]!

def Opcode.mnemonic (op : Opcode) : String := op.info.mnemonic

instance : ToString Opcode := ⟨Opcode.mnemonic⟩

/-- The opcode of mnemonic `m`. -/
def Opcode.ofMnemonic? (m : String) : Option Opcode :=
  all.find? fun op => op.mnemonic == m

namespace Opcode

",
    );
    for (i, info) in infos.iter().enumerate() {
        writeln!(s, "/-- `{}` -/\ndef {} : Opcode := ⟨{i}⟩", info.mnemonic, camel(&format!("{:?}", info.opcode))).unwrap();
    }
    writeln!(s, "\nend Opcode\n\nend Ryo.Vm.{ns}").unwrap();
}

