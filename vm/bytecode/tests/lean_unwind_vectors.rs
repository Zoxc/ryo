//! Test vectors for the Lean unwind-table readers (`lean/Ryo/Obj/EhFrame.lean`,
//! `lean/Ryo/Obj/Lsda.lean`): `.eh_frame` bytes from `image::eh_cie` and `image::eh_fde` for
//! functions in both frame modes (with and without the entry's counter stub, frame sizes
//! across the `uleb128`, probe and advance-width boundaries), and LSDAs from `asm::lsda::write`
//! with mutations, each with Rust's `asm::lsda::parse` verdict. Written as
//! `lean/RyoTest/UnwindVectors.lean`, which `RyoTest/Unwind.lean` checks; with `RYO_LEAN_GEN=1`
//! the test rewrites that file, else it checks it is up to date.

use std::fmt::Write as _;

use ryo_bytecode::asm::{self, CallSite, Mode, lsda};
use ryo_bytecode::image::{EhFunc, eh_cie, eh_fde};

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn sites_text(s: &Option<Vec<CallSite>>) -> String {
    match s {
        None => "none".into(),
        Some(v) => v.iter().map(|c| format!("{} {} {} {};", c.start, c.len, c.pad.map_or(-1, |p| p as i64), c.catch as u8)).collect(),
    }
}

fn vectors() -> String {
    let mut s = String::new();
    s.push_str(
        "/-\nGenerated by `vm/bytecode/tests/lean_unwind_vectors.rs` (`RYO_LEAN_GEN=1 cargo test --test\nlean_unwind_vectors` in `vm/`): \
         `.eh_frame` bytes of `image::eh_cie` and `image::eh_fde`, and LSDAs with Rust's\n`asm::lsda::parse` verdict, which \
         `RyoTest/Unwind.lean` checks. Do not edit.\n-/\n\nnamespace RyoTest.UnwindVectors\n\n",
    );
    s.push_str(
        "/-- A CIE and one FDE: the function's `EhFunc` fields, its mode, `asm::prologue_len`, the bytes, and\nthe \
         positions of the FDE and of its `pc_begin` and LSDA fields. -/\nstructure Fde where\n  framePointer : Bool\n  len : Nat\n  \
         frameSize : Nat\n  prologue : Nat\n  entryStub : Nat\n  prologueLen : Nat\n  eh : String\n  fde : Nat\n  pcBegin : Nat\n  \
         lsda : Nat\n\n",
    );
    s.push_str("def fdes : List Fde := [\n");
    let mut first = true;
    for fp in [false, true] {
        let mode = Mode { fp_arg: true, frame_pointer: fp, align_loops: false, pe: false, counters: true, far_rt: false };
        for frame_size in [0u32, 8, 104, 112, 200, 4080, 4096, 70000] {
            for prologue in [0u32, 7] {
                for (len, stub) in [(60u32, None), (300, Some(250)), (70000, Some(69990)), (40, Some(30))] {
                    let pl = asm::prologue_len(frame_size, mode);
                    let entry_stub = stub.unwrap_or(len);
                    if prologue + pl + 4 > entry_stub.min(len) {
                        continue;
                    }
                    let mut eh = Vec::new();
                    eh_cie(&mut eh);
                    let at = eh.len();
                    let f = eh_fde(&mut eh, 0, &EhFunc { len, frame_size, prologue, entry_stub }, mode);
                    if !first {
                        s.push_str(",\n");
                    }
                    first = false;
                    write!(
                        s,
                        "  {{ framePointer := {fp}, len := {len}, frameSize := {frame_size}, prologue := {prologue}, entryStub := {entry_stub}, \
                         prologueLen := {pl},\n    eh := \"{}\", fde := {at}, pcBegin := {}, lsda := {} }}",
                        hex(&eh),
                        f.pc_begin,
                        f.lsda
                    )
                    .unwrap();
                }
            }
        }
    }
    s.push_str("\n]\n\n");
    s.push_str(
        "/-- LSDA bytes and what `lsda::parse` makes of them: `none`, or per call site `<start> <len> <pad or -1> \
         <catch>;`. -/\nstructure Lsda where\n  bytes : String\n  out : String\n\n",
    );
    s.push_str("def lsdas : List Lsda := [\n");
    let mut rng = Rng(0x9e3779b97f4a7c15);
    let mut cases: Vec<Vec<u8>> = Vec::new();
    for k in 0..60 {
        let n = if k < 4 { k } else { rng.below(6) };
        let mut sites = Vec::new();
        let mut pos = 0u32;
        let big = k % 7 == 0;
        for _ in 0..n {
            pos += rng.below(if big { 1 << 20 } else { 200 }) as u32;
            let len = 1 + rng.below(if big { 1 << 16 } else { 20 }) as u32;
            let pad = (rng.below(3) != 0).then(|| rng.below(if big { u32::MAX as u64 } else { 400 }) as u32 + 1);
            let catch = pad.is_some() && rng.below(3) == 0;
            sites.push(CallSite { start: pos, len, pad, catch });
            pos += len;
        }
        let b = lsda::write(&sites);
        assert_eq!(lsda::parse(&b).as_ref(), Some(&sites));
        cases.push(b.clone());
        // Mutations: a byte changed, the end cut, a byte appended.
        for _ in 0..4 {
            let mut m = b.clone();
            match rng.below(4) {
                0 => {
                    let i = rng.below(m.len() as u64) as usize;
                    m[i] = rng.below(256) as u8;
                }
                1 => {
                    let i = rng.below(m.len() as u64) as usize;
                    m[i] ^= 1 << rng.below(8);
                }
                2 => {
                    m.truncate(rng.below(m.len() as u64) as usize);
                }
                _ => m.push(rng.below(256) as u8),
            }
            cases.push(m);
        }
    }
    // Hand-picked: bad headers, action 2, action 1 without a pad, the action record missing or
    // extra, non-canonical and overlong `uleb128`s, values past `u32`.
    for h in [
        "",
        "ffff",
        "ffff0100",
        "feff0100",
        "ff000100",
        "ffff0300",
        "ffff010400000002",
        "ffff010400000001",
        "ffff010401020301",
        "ffff0104010203010100",
        "ffff01040102030100",
        "ffff010401020300",
        "ffff0104010203000100",
        "ffff018000",
        "ffff01800000",
        "ffff010580000203000000",
        "ffff0105800002030000",
        "ffff0105010203800000",
        "ffff010affffffff0f01020300",
        "ffff010bffffffff1f0102030000",
        "ffff010c808080808000010203000000",
        "ffff010d80808080808000010203000000",
        "ffff0108010203000405060700",
        "ffff01080102030004050607",
    ] {
        cases.push((0..h.len()).step_by(2).map(|i| u8::from_str_radix(&h[i..i + 2], 16).unwrap()).collect());
    }
    for (k, b) in cases.iter().enumerate() {
        let sep = if k + 1 == cases.len() { "" } else { "," };
        writeln!(s, "  {{ bytes := \"{}\", out := \"{}\" }}{sep}", hex(b), sites_text(&lsda::parse(b))).unwrap();
    }
    s.push_str("]\n\nend RyoTest.UnwindVectors\n");
    s
}

#[test]
fn lean_unwind_vectors() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../lean/RyoTest/UnwindVectors.lean");
    let want = vectors();
    if std::env::var_os("RYO_LEAN_GEN").is_some_and(|v| v == "1") {
        std::fs::write(path, want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(path).unwrap_or_default();
    assert!(have == want, "{path} is out of date: regenerate it with RYO_LEAN_GEN=1 cargo test --test lean_unwind_vectors");
}
