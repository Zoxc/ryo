//! The reduced instruction set against the full one: the same instructions, the ones that
//! run as native code, and `handler`.

use ryo_bytecode::asm;
use ryo_bytecode::full;
use ryo_bytecode::full::{List, Neg, Target, list_words};
use ryo_bytecode::reduced::{self, Arg, Handler, Insn, Opcode};

/// `src/isa/reduced_ops.rs` is generated: the header, the entries of
/// `src/isa/full_ops.rs` that run as
/// native code (`asm::has_inline || !asm::has_handler`), in order (a family's with its widths
/// cut down to theirs), and the `handler` entry.
/// With `RYO_GEN=1` this test rewrites it, else it checks it is up to date.
#[test]
fn reduced_ops_generated() {
    let dir = env!("CARGO_MANIFEST_DIR");
    let path = format!("{dir}/src/isa/reduced_ops.rs");
    let ops = std::fs::read_to_string(format!("{dir}/src/isa/full_ops.rs")).unwrap();
    let have = std::fs::read_to_string(&path).unwrap();
    let mut want = String::from(REDUCED_HEADER);
    let is_native = |f: full::Opcode| asm::has_inline(f) || !asm::has_handler(f);
    let mut native = full::ALL_OPCODES.iter().copied().filter(|&f| is_native(f));
    let mut next = native.next();
    for line in ops.lines() {
        let t = line.trim_start();
        if let Some(fam) = t.strip_prefix("fam ") {
            // A family: its native members, with the widths list cut down to theirs.
            let name: String = fam.split(" = ").next().unwrap().split(" * ").collect();
            let f = *full::Family::ALL.iter().find(|f| format!("{f:?}") == name).unwrap();
            let ws: Vec<_> = f.members().filter(|&op| is_native(op)).collect();
            if ws.is_empty() {
                continue;
            }
            for &op in &ws {
                assert_eq!(next, Some(op), "{op:?}: not in full_ops.rs's order");
                next = native.next();
            }
            let at = line.rfind(" @ [").unwrap();
            let list: Vec<String> = ws.iter().map(|op| format!("{:?}", op.width().unwrap())).collect();
            want.push_str(&format!("{} @ [{}],\n", &line[..at], list.join(", ")));
            continue;
        }
        let Some((name, _)) = t.split_once(" = \"") else { continue };
        if let Some(f) = next
            && format!("{f:?}") == name
        {
            want.push_str(line);
            want.push('\n');
            next = native.next();
        }
    }
    assert_eq!(next, None, "{next:?}: not found in full_ops.rs in list order");
    want.push_str(REDUCED_HANDLER);
    if std::env::var_os("RYO_GEN").is_some_and(|v| v == "1") {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    assert!(have == want, "{path} is out of date: regenerate it with RYO_GEN=1 cargo test --test reduced");
}

const REDUCED_HEADER: &str = "\
// Generated by `vm/bytecode/tests/reduced.rs` (`RYO_GEN=1 cargo test --test reduced` in `vm/`):
// do not edit. The reduced opcode list (design/vm.md, \"Reduced instructions\"): the opcodes
// of the full list (full_ops.rs) that run as native code, the inline ones and those without a
// handler, with the same mnemonics, shapes and operands, in the same order, and `handler` for
// every handler call. Its numbering is its own; nothing stores it, so it has no format version.

define_ops! {
";

const REDUCED_HANDLER: &str = "    // A call of the handler of the full opcode `h` with the argument registers `args`
    // from `rdi` on, then the control flow of `h`'s shape: with `br` a branch to `t[0]` on
    // the returned `bool` (polarity `neg`), with `switch` a jump through the table `t` on
    // the returned index (the default last). `neg` is 0 and `t` empty for the others.
    Handler = \"handler\" op { h: Handler, args: Args, neg: Neg, t: Targets },
}
";

#[test]
fn subset_of_the_full_set() {
    // Every reduced opcode but `handler` is a full one with the same mnemonic, shape and
    // operands, in the full list's order.
    let mut last = None;
    for &op in reduced::ALL_OPCODES {
        let info = op.info();
        let Some(f) = op.full() else {
            assert_eq!(op, Opcode::Handler);
            continue;
        };
        let fi = f.info();
        assert_eq!((info.mnemonic, info.shape, info.operands), (fi.mnemonic, fi.shape, fi.operands), "{op:?}");
        assert_eq!(format!("{op:?}"), format!("{f:?}"));
        assert_eq!(Opcode::of_full(f), Some(op));
        assert!(last < Some(f), "{op:?} out of the full list's order");
        last = Some(f);
    }
    // And they are exactly those that run as native code.
    for &f in full::ALL_OPCODES {
        assert_eq!(Opcode::of_full(f).is_some(), asm::has_inline(f) || !asm::has_handler(f), "{f:?}");
    }
}

#[test]
fn handler_round_trips() {
    let args = list_words([Arg::Fp, Arg::Imm(u64::MAX - 5), Arg::Const(full::Const(8)), Arg::Ro(16)]);
    let t = list_words([Target(-3)]);
    let insn = Insn::Handler { h: Handler(full::Opcode::DivSW32), args: List::from_words(&args), neg: Neg(true), t: List::from_words(&t) };
    let mut w = Vec::new();
    insn.encode(&mut w);
    assert_eq!(Insn::decode(&w), Ok((insn, w.len())));
    assert_eq!(insn.to_string(), "handler! div.s.w32, [fp, 0xfffffffffffffffa, k8, ro16], [@-3]");
    // Handlers only of full opcodes with one, and valid arguments.
    let mut bad = w.clone();
    bad[1] = full::Opcode::Jmp as u32;
    assert!(Insn::decode(&bad).is_err());
    let mut bad = w.clone();
    bad[3] = 8;
    assert!(Insn::decode(&bad).is_err());
}
